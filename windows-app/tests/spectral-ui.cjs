    await page.locator('#app-version').filter({hasText:`v${require('../package.json').version}`}).waitFor();
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(1366,768));
    await page.waitForFunction(()=>innerWidth===1366&&innerHeight===768);
    await page.locator('[data-tab="analysis"]').click();
    await page.locator('#analysis-source-waveform').click();
    assert(await page.locator('#spectral-empty').isVisible());
    assert((await page.locator('.spectral-capability').textContent()).includes('ยังทำ FFT สด') || (await page.locator('.spectral-capability').textContent()).includes('ยังไม่พบช่องส่งคลื่น'));
    const importFile=async file=>{
      await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},file);
      await page.locator('#spectral-import').click();
    };
    await page.locator('#spectral-unit').selectOption('m/s²');
    await importFile(waveform);
    await page.locator('#spectral-status').filter({hasText:'วิเคราะห์ waveform.csv'}).waitFor();
    await page.locator('#spectral-peak').filter({hasText:'50 Hz'}).waitFor();
    assert((await page.locator('#spectral-peak').textContent()).includes('1 m/s²'));
    assert((await page.locator('#spectral-metadata').textContent()).includes('Δf 2 Hz'));
    assert((await page.locator('#spectral-metadata').textContent()).includes('15 ช่วง'));
    assert.equal(await page.locator('#spectral-frame').getAttribute('max'),'14');
    assert.equal(await page.locator('#spectral-source').textContent(),'WAVEFORM CSV · ไฟล์คลื่น');
    assert(await page.locator('#spectral-fs').isDisabled());assert(await page.locator('#spectral-unit').isDisabled(),'settings cannot contradict the loaded waveform');
    assert.equal(await page.locator('#spectral-view').inputValue(),'surface','new analysis opens as a continuous colored 3D surface');
    await page.locator('#spectral-surface-title').filter({hasText:'Surface 3D'}).waitFor();
    assert(await page.locator('#spectral-max-hz').isEnabled());
    await page.locator('#spectral-max-hz').fill('200');await page.locator('#spectral-max-hz').press('Tab');
    await settlePlot();
    // The mesh must paint a filled, height-colored area, rather than line curtains.
    await page.waitForFunction(()=>{const c=document.getElementById('spectral-surface'),data=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let colored=0;for(let i=0;i<data.length;i+=4)if(data[i+3]>0&&Math.max(data[i],data[i+1],data[i+2])-Math.min(data[i],data[i+1],data[i+2])>100)colored++;return colored>2000;});
    await page.locator('#spectral-surface').scrollIntoViewIfNeeded();
    const meshPoint=await page.locator('#spectral-surface').evaluate(c=>{const d=c.getContext('2d').getImageData(0,0,c.width,c.height).data,r=c.getBoundingClientRect();for(let y=26;y<c.height-26;y++)for(let x=81;x<c.width-81;x++){const i=(y*c.width+x)*4;if(d[i]>150&&d[i+2]>100&&d[i+1]<90&&d[i+3]===255&&[i-4,i+4,i-c.width*4,i+c.width*4].every(p=>d[p+3]===255&&Math.max(d[p],d[p+1],d[p+2])-Math.min(d[p],d[p+1],d[p+2])>100))return{x:r.x+(x+.5)*r.width/c.width,y:r.y+(y+.5)*r.height/c.height};}return null;});
    assert(meshPoint,'a nonzero spectral peak has a high color on the filled surface');
    await page.mouse.move(meshPoint.x,meshPoint.y);await page.locator('#spectral-readout').filter({hasText:'จุด FFT จริง'}).waitFor();
    await page.mouse.click(meshPoint.x,meshPoint.y);
    await page.screenshot({path:path.join(artifacts,'spectral-surface.png'),animations:'disabled'});
    await page.locator('#spectral-frame').fill('0');
    await page.locator('#spectral-view').selectOption('waterfall');
    const painted=await page.locator('#spectral-surface').evaluate(canvas=>{const p=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;let count=0;for(let i=3;i<p.length;i+=4)if(p[i])count++;return count;});
    assert(painted>1000,'actual waterfall geometry is painted');
    await page.locator('#spectral-surface').focus();await page.keyboard.press('ArrowRight');
    await page.locator('#spectral-frame-time').filter({hasText:'2/15'}).waitFor();
    const box=await page.locator('#spectral-surface').boundingBox();
    await page.mouse.move(box.x+box.width*.4,box.y+box.height*.5);await page.mouse.down();await page.mouse.move(box.x+box.width*.6,box.y+box.height*.5);await page.mouse.up();
    await page.locator('#spectral-reset').click();
    await page.locator('#spectral-view').selectOption('spectrogram');
    await page.locator('#spectral-surface-title').filter({hasText:'Spectrogram'}).waitFor();
    assert(await page.locator('#spectral-reset').isDisabled());
    const heatmap=await page.locator('#spectral-surface').boundingBox();
    await page.mouse.move(heatmap.x+heatmap.width/2,heatmap.y+heatmap.height/2);
    await page.locator('#spectral-readout').filter({hasText:'Hz ·'}).waitFor();
    await page.mouse.click(heatmap.x+heatmap.width/2,heatmap.y+heatmap.height/2);
    assert.notEqual(await page.locator('#spectral-frame').inputValue(),'1','clicking the spectrogram chooses its actual FFT frame');
    await page.locator('#spectral-scale').selectOption('psd');
    await page.locator('#spectral-fft-title').filter({hasText:'PSD'}).waitFor();
    assert((await page.locator('#spectral-peak').textContent()).includes('(m/s²)²/Hz'));
    await page.locator('#spectral-axis').selectOption('Y');
    await page.locator('#spectral-peak').filter({hasText:'80 Hz'}).waitFor();
    await page.locator('#spectral-fullscreen').click();
    await page.waitForFunction(()=>document.fullscreenElement?.id==='spectral-panel');
    await page.keyboard.press('Escape');await page.waitForFunction(()=>!document.fullscreenElement);
    for(const [width,height]of[[1366,700],[1024,768],[768,1024],[960,680]]){
      await page.setViewportSize({width,height});
      await page.locator('#spectral-view').selectOption('surface');
      await page.locator('#spectral-surface').scrollIntoViewIfNeeded();
      await settlePlot();
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`no page horizontal overflow ${width}`);
      const overflow=await page.locator('#analysis-view').evaluate(el=>el.scrollWidth>el.clientWidth+1);
      assert(!overflow,`no analysis overflow ${width}`);
      const point=await page.locator('#spectral-surface').evaluate(c=>{const d=c.getContext('2d').getImageData(0,0,c.width,c.height).data,r=c.getBoundingClientRect();for(let y=30;y<c.height-30;y++)for(let x=80;x<c.width-80;x++){const i=(y*c.width+x)*4;if(d[i]>150&&d[i+2]>100&&d[i+1]<90&&d[i+3]===255&&[i-4,i+4,i-c.width*4,i+c.width*4].every(p=>d[p+3]===255))return{x:r.x+(x+.5)*r.width/c.width,y:r.y+(y+.5)*r.height/c.height};}return null;});
      assert(point,`${width}: surface peak is visible`);
      await page.locator('#spectral-readout').evaluate(el=>{el.textContent='';});
      await page.mouse.move(point.x,point.y);await page.locator('#spectral-readout').filter({hasText:'จุด FFT จริง'}).waitFor();
      if(width===1366)await page.screenshot({path:path.join(artifacts,'spectral-waterfall.png'),fullPage:false});
    }
    await page.setViewportSize({width:1366,height:768});
    await importFile(aggregate);
    await page.locator('#spectral-status.error').filter({hasText:'ไม่ใช่ waveform'}).waitFor();
    assert(!(await page.locator('#spectral-status').textContent()).includes('คอลัมน์มากเกิน'),'a real recording export explains its type rather than column count');
    assert(await page.locator('#spectral-results').isHidden(),'rejected CSV cannot leave stale spectra visible');
    await page.locator('#spectral-open-history').click();assert(await page.locator('#analysis-history').isVisible());
    await page.locator('#analysis-source-waveform').click();
    await importFile(gap);await page.locator('#spectral-status.error').waitFor();
    assert(await page.locator('#spectral-results').isHidden());
    await page.locator('#spectral-demo').click();
    await page.locator('#spectral-source').filter({hasText:'TEST SIGNAL'}).waitFor();
    await page.locator('#spectral-metadata').filter({hasText:'Fs 2,048 Hz'}).waitFor();
    await page.locator('#spectral-scale').selectOption('amplitude');
    await page.locator('#spectral-view').selectOption('waterfall');
    await page.locator('#spectral-peak').filter({hasText:'50 Hz'}).waitFor();
