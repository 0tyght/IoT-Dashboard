  fs.writeFileSync(waveform,'time_s,x,y,z\n'+Array.from({length:count},(_,i)=>{const t=i/fsHz;return `${t},${Math.sin(2*Math.PI*50*t)+.4*Math.sin(2*Math.PI*120*t)},${.7*Math.sin(2*Math.PI*80*t)},${.5*Math.sin(2*Math.PI*200*t)}`;}).join('\n'));
  fs.writeFileSync(aggregate,'\uFEFF'+CSV_KEYS.join(',')+'\r\n'+csvRow({timestamp:'2026-10-21T00:00:00Z',motorId:'MTR-01',value:2.4,unit:'mm/s',channels:{velocityX:1,velocityY:2.4,velocityZ:1.5}}));
